#if DEBUG
import Foundation

/// Stub data so the setup and mods flows can be exercised in the simulator without a Mac
/// build or real mods. Everything goes through the real installer / library code.
///
/// Launch arguments (Xcode scheme or `simctl launch … -FF7Reset`):
///   -FF7Reset        delete the installed game, mods and profile first
///   -FF7SampleGame   install a generated stub GamePackage
///   -FF7SampleMods   import three sample mods (two folders with mod.xml, one .iro)
enum SampleData {
    static func applyLaunchArguments(paths: AppPaths, installer: GameInstalling, library: ModLibrary) {
        let args = ProcessInfo.processInfo.arguments
        if args.contains("-FF7Reset") {
            try? FileManager.default.removeItem(at: paths.root)
        }
        if args.contains("-FF7SampleGame"), installer.installedPackage() == nil,
           let folder = try? makeSamplePackageFolder() {
            _ = try? installer.importPackage(from: folder) { _ in }
        }
        if args.contains("-FF7SampleMods") {
            try? importSampleMods(into: library)
        }
    }

    private static func scratch(_ name: String) throws -> URL {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("ff7-sample-\(UUID().uuidString)", isDirectory: true)
            .appendingPathComponent(name, isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }

    /// An unpacked stub package whose manifest lists one (hashed) file.
    static func makeSamplePackageFolder() throws -> URL {
        let dir = try scratch("Sample.ff7pkg")
        let readme = Data("Sample GamePackage generated by the iOS app (DEBUG). No game code.\n".utf8)
        let readmeURL = dir.appendingPathComponent("README.txt")
        try readme.write(to: readmeURL)
        let manifest: [String: Any] = [
            "format": GameManifest.supportedFormat,
            "tool_version": "sample",
            "created_at": ISO8601DateFormatter().string(from: Date()),
            "exe_name": "ff7_en.exe",
            "exe_sha256": String(repeating: "5a", count: 32),
            "exe_size": 0,
            "language": "en",
            "build_id": "sample-\(Int(Date().timeIntervalSince1970))",
            "core_version": EngineBridge.version(),
            "platform": GameManifest.supportedPlatform,
            "notes": "Sample stub package (DEBUG build).",
            "files": [[
                "path": "README.txt",
                "sha256": try GamePackageValidator.sha256(of: readmeURL),
                "size": readme.count,
            ]],
        ]
        let json = try JSONSerialization.data(withJSONObject: manifest, options: [.prettyPrinted, .sortedKeys])
        try json.write(to: dir.appendingPathComponent(GamePackageLayout.manifest))
        return dir
    }

    static func importSampleMods(into library: ModLibrary) throws {
        let mods: [(folder: String, name: String, author: String, category: String)] = [
            ("SampleFieldTextures", "Sample Field Textures", "FF7Recomp", "Backgrounds"),
            ("SampleMenuOverhaul", "Sample Menu Overhaul", "FF7Recomp", "User Interface"),
        ]
        for mod in mods {
            let dir = try scratch(mod.folder)
            let xml = """
            <?xml version="1.0" encoding="utf-8"?>
            <ModInfo>
              <ID>\(UUID().uuidString.lowercased())</ID>
              <Name>\(mod.name)</Name>
              <Author>\(mod.author)</Author>
              <Version>1.0</Version>
              <Category>\(mod.category)</Category>
              <Description>Placeholder mod for testing the launcher.</Description>
            </ModInfo>
            """
            try Data(xml.utf8).write(to: dir.appendingPathComponent("mod.xml"))
            try library.importMod(from: dir)
        }
        let iro = try scratch("iro").appendingPathComponent("SampleArchive.iro")
        try Data("IROS".utf8).write(to: iro)
        try library.importMod(from: iro)
    }
}
#endif
